/**
 * Chart-reading lessons ("อ่านกราฟเทคนิค"): short slide decks over real price history, with the
 * chart annotated where the lesson points. Every date below was checked against the bundled data
 * (see chartLessons.test.ts), so the candles really have the shape the text describes.
 */

export type Indicator = 'ema20' | 'ma50' | 'ma200' | 'volume' | 'rsi';
export type Tone = 'up' | 'down' | 'info';

/** A point on a candle: one of its four prices on a given day. */
export interface Anchor {
  date: string;
  at: 'high' | 'low' | 'open' | 'close';
}

export type Annotation =
  /** Arrow or dot on one candle, with a short label. */
  | { kind: 'mark'; date: string; text: string; tone?: Tone; pos?: 'above' | 'below' }
  /** Fade every candle except those in [from, to] (one day when `to` is omitted). */
  | { kind: 'focus'; from: string; to?: string }
  /** Straight line through two candles, optionally extended to a later date. */
  | { kind: 'trend'; a: Anchor; b: Anchor; until?: string; tone?: Tone }
  /** Horizontal line at the highest high / lowest low between two dates, drawn on to `until`. */
  | { kind: 'level'; from: string; to: string; at: 'high' | 'low'; until?: string; tone?: Tone };

export interface QuizOption {
  label: string;
  correct?: boolean;
  why: string;
}

export interface LessonSlide {
  title: string;
  text: string;
  /** Show the labelled candle diagram instead of a chart. */
  anatomy?: boolean;
  chart?: {
    ticker: string;
    from: string;
    to: string;
    indicators?: Indicator[];
    annotations?: Annotation[];
  };
  quiz?: { question: string; options: QuizOption[] };
  /** "Click where the level is": the answer is the level annotation's price, within `tol` (fraction). */
  pick?: { prompt: string; level: { from: string; to: string; at: 'high' | 'low' }; tol: number; ok: string; miss: string };
  /** Run simple strategies against buy-and-hold on these tickers (from `from` to the end of the data). */
  backtest?: { tickers: string[]; from: string };
}

export interface ChartLesson {
  id: string;
  number: number;
  title: string;
  concept: string;
  slides: LessonSlide[];
  takeaways: string[];
}

