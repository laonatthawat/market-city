/**
 * Exponential moving average (weight 2/(period+1) on the newest price), seeded with the SMA of the
 * first `period` values; null before that.
 */
export function ema(values: readonly number[], period: number): (number | null)[] {
  const out: (number | null)[] = new Array(values.length).fill(null);
  if (values.length < period) return out;
  const k = 2 / (period + 1);
  let prev = 0;
  for (let i = 0; i < period; i++) prev += values[i] / period;
  out[period - 1] = prev;
  for (let i = period; i < values.length; i++) {
    prev = values[i] * k + prev * (1 - k);
    out[i] = prev;
  }
  return out;
}

export function rsi(values: readonly number[], period = 14): (number | null)[] {
  const out: (number | null)[] = new Array(values.length).fill(null);
  if (values.length <= period) return out;
  let gain = 0;
  let loss = 0;
  for (let i = 1; i <= period; i++) {
    const d = values[i] - values[i - 1];
    if (d >= 0) gain += d;
    else loss -= d;
  }
  gain /= period;
  loss /= period;
  out[period] = loss === 0 ? 100 : 100 - 100 / (1 + gain / loss);
  for (let i = period + 1; i < values.length; i++) {
    const d = values[i] - values[i - 1];
    gain = (gain * (period - 1) + Math.max(d, 0)) / period;
    loss = (loss * (period - 1) + Math.max(-d, 0)) / period;
    out[i] = loss === 0 ? 100 : 100 - 100 / (1 + gain / loss);
  }
  return out;
}

/** Fractional change between the value `lookback` steps ago and the last value. */
export function changeOver(values: ArrayLike<number>, lookback: number): number | null {
  if (values.length < 2) return null;
  const i = Math.max(0, values.length - 1 - lookback);
  const base = values[i];
  return base > 0 ? values[values.length - 1] / base - 1 : null;
}

/** Annualized volatility of daily log returns over the last `window` values. */
export function annualizedVol(values: ArrayLike<number>, window = 20): number | null {
  const n = Math.min(window, values.length - 1);
  if (n < 2) return null;
  const rets: number[] = [];
  for (let i = values.length - n; i < values.length; i++) rets.push(Math.log(values[i] / values[i - 1]));
  const mean = rets.reduce((a, b) => a + b, 0) / rets.length;
  const variance = rets.reduce((a, b) => a + (b - mean) ** 2, 0) / (rets.length - 1);
  return Math.sqrt(variance * 252);
}
